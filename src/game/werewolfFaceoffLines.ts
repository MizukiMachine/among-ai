export function isWerewolfFaceoffRole(role: Role): role is WerewolfFaceoffRole {
  return werewolfFaceoffRoles.includes(role as WerewolfFaceoffRole);
}

function fallbackWerewolfFaceoffLines(name: string, role: string): readonly [string, string, string] {
  return [
    `${name}、${role}です。人間側の顔で潜り、村を騙します`,
    `${name}は${role}です。昼は信用を取り、疑いをそらします`,
    `${name}、${role}です。自然に混ざって、票の流れを動かします`
  ];
}

export function werewolfFaceoffLineOptionsForPlayer(
  player: WerewolfFaceoffSpeaker,
  language = defaultLanguage
): readonly [string, string, string] {
  const role = isWerewolfFaceoffRole(player.role) ? player.role : "Werewolf";
  const characterName = player.characterProfile?.nameJa ?? player.name;
  const characterLines = japaneseCharacterWerewolfFaceoffLines[characterName]?.[role];
  if (characterLines) {
    return characterLines;
  }
  return fallbackWerewolfFaceoffLines(player.name, roleLabel(role, language));
}
