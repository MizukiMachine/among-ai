export const characterNames = characterProfiles.map((profile) => profile.nameJa);

const profilesById = new Map(characterProfiles.map((profile) => [profile.playerId, profile]));

export function getCharacterProfile(playerId: string): CharacterProfile | undefined {
  return profilesById.get(playerId);
}

export function getPersonaForPlayer(playerId: string): Persona | undefined {
  return getCharacterProfile(playerId)?.persona;
}

export function characterVoiceSection(profile: CharacterProfile): string {
  const lines = [
    `キャラクター名: ${profile.nameJa}（${profile.gender === "male" ? "男" : "女"}）`,
    `キャッチフレーズ: ${profile.tagline}`,
    `話し方: ${profile.speechStyle}`,
    `価値観: ${profile.values}`,
    `発言例:`,
    ...profile.sampleLines.map((line) => `  - "${line}"`)
  ];

  const relationEntries = Object.entries(profile.relations);
  if (relationEntries.length > 0) {
    lines.push("他プレイヤーへの想い:");
    lines.push(...relationEntries.map(([id, text]) => `  - ${id}: ${text}`));
  }

  return lines.join("\n");
}
